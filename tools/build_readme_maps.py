#!/usr/bin/env python3
"""Write the maps section of README.md from vb/maps-data.js.

    python3 tools/build_readme_maps.py

The map data comes from the BAR-Maps repository (tools/collect_map_stats.py), so
the table in the README and the page on the website always say the same thing.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DATA = os.path.join(ROOT, "vb", "maps-data.js")
README = os.path.join(ROOT, "README.md")

BAR = "https://raw.githubusercontent.com/bitopsy/BAR-Maps/master/"
VB = "https://raw.githubusercontent.com/bitopsy/voidborn/master/"

MARK = "<!-- maps: generated by tools/build_readme_maps.py -->"


def load():
    src = open(DATA, encoding="utf-8").read()
    return json.loads(src[src.index("["):src.rindex(";")])


def size_of(m):
    s = m.get("size") or ""
    mm = re.search(r"\(([\d,]+ x [\d,]+) elmos\)", s)
    return mm.group(1) if mm else s.split("(")[0].strip()


def preview_of(m):
    """The preview as GitHub can show it: the webp of the site for the official
    map, the original picture in the map repository for the others."""
    if m.get("official"):
        return VB + "vb/img/voidborn-rift.webp"
    return BAR + m["id"] + "/" + os.path.basename(m["preview"]).replace(".webp", ".png")


def download_of(m):
    if m.get("official"):
        return VB + "dist/voidborn_rift.sd7"
    return "https://github.com/bitopsy/BAR-Maps/raw/master/" + m["archive"]


def docs_of(m):
    if m.get("official"):
        return "https://github.com/bitopsy/voidborn/blob/master/map/mapinfo.lua"
    return "https://github.com/bitopsy/BAR-Maps/tree/master/" + m["id"]


def section(maps):
    out = []
    out.append("## Maps")
    out.append("")
    out.append("**Voidborn Rift** is the official map: two symmetric home asteroids (west/east, 10 metal spots each), a central")
    out.append("Eye ring (5), north/south islands (3 each), four corner islands (2 each) and floating debris (1 each) &ndash;")
    out.append("43 metal spots in total, 2&ndash;4 players. It is part of the game (`dist/voidborn_rift.sd7`).")
    out.append("")
    out.append("Around it is a family of arenas in the [BAR-Maps repository](https://github.com/bitopsy/BAR-Maps): each one")
    out.append("with its own archive, minimap and documentation file. Drop a `.sd7` into the `maps/` folder of your engine data")
    out.append("directory and it shows up in the map list of the game &ndash; no rebuild needed.")
    out.append("")
    out.append(MARK)
    out.append("")
    out.append("| Map | Preview | Size | Start spots | Mexes | Metal/s | Download | Docs |")
    out.append("|---|---|---|---|---|---|---|---|")
    for m in maps:
        name = m.get("name") or m["id"]
        if m.get("official"):
            name = "**" + name + "** (official)"
        arch = m.get("archive_size") or ""
        if m.get("has_archive") is False:
            dl = "&mdash; no archive yet"
        else:
            dl = "[%s](%s)" % (arch or "?", download_of(m))
        out.append("| %s | ![%s](%s) | %s | %s | %s | %s | %s | [md](%s) |" % (
            name, name, preview_of(m),
            size_of(m),
            m.get("players") or "&mdash;",
            m.get("mexes") or "&mdash;",
            m.get("metal_s") or "&mdash;",
            dl, docs_of(m)))
    out.append("")
    out.append("The numbers come out of the map archives themselves (`tools/collect_map_stats.py` reads them with")
    out.append("`bar_map_stats.py`), so they describe what is really in the map. The website has the same list with the full")
    out.append("description of every map: <https://f33.fr/vb/maps.html>")
    out.append("")
    return "\n".join(out)


def main():
    maps = load()
    new = section(maps)
    src = open(README, encoding="utf-8").read()
    # replace the section that is already there: the generated one (it carries the
    # marker) or the old hand written one
    m = re.search(r"^## Maps\n.*?(?=^## )", src, re.S | re.M)
    if m:
        src = src[:m.start()] + new + "\n" + src[m.end():]
    else:
        m = re.search(r"^## Map: Voidborn Rift.*?(?=^## )", src, re.S | re.M)
        if m:
            src = src[:m.start()] + new + "\n" + src[m.end():]
        else:
            src = src.replace("## Units", new + "\n## Units", 1)
    open(README, "w", encoding="utf-8").write(src)
    print("README maps section written,", len(maps), "maps")


if __name__ == "__main__":
    main()
